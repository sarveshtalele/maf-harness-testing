"""Verification triage (accuracy 7.4): sort each failing executed case by evidence, never by a model call.

Classes:
- ``product_defect``: the oracle is ``specified`` or ``golden``, the failure shows actual != expected, and the documented
  quote states the expected value the test asserts. The test is kept; the report carries the quote, actual and expected.
- ``test_defect``: the expectation was not documented (oracle ``derived``, ``characterization`` or missing), or the
  documented quote does not state the asserted value (the expectation was guessed), or the generated test cannot run
  (import, name, syntax or compile error). Only these are regenerated by the heal loop.
- ``environment``: the existing error taxonomy (``errors.classify``) names an environment or infrastructure cause.
- ``unresolved``: anything the rules cannot decide (for example an application exception with no actual/expected pair,
  or a metamorphic/property oracle). It is reported, never repaired automatically.

``verified`` is a separate, stricter fact: source-review accepted AND execution passed (see ``is_verified``).
"""

from __future__ import annotations

import re
from typing import Any

from .. import errors
from . import triage as triage_rules

PRODUCT_DEFECT = "product_defect"
TEST_DEFECT = "test_defect"
ENVIRONMENT = "environment"
UNRESOLVED = "unresolved"
CLASSES = (PRODUCT_DEFECT, TEST_DEFECT, ENVIRONMENT, UNRESOLVED)

DOCUMENTED_ORACLES = frozenset({"specified", "golden"})
GUESSABLE_ORACLES = frozenset({"derived", "characterization", ""})
# Where the documented quote may sit on a design case; the first non-empty value wins.
QUOTE_KEYS = ("oracle_quote", "expectation_quote", "documented_quote")

_PYTEST_ASSERT = re.compile(r"\bassert\s+(?P<actual>.+?)\s+==\s+(?P<expected>.+?)\s*$", re.M)
_EXPECTED_GOT = re.compile(
    r"expected:?\s*<?(?P<expected>[^<>\n]+?)>?\s+(?:got|but was):?\s*<?(?P<actual>[^<>\n]+?)>?\s*$",
    re.I | re.M,
)
_ENVIRONMENT_CATEGORIES = frozenset({"environment", "infra"})


def oracle_kind(case: dict[str, Any]) -> str:
    """The design case's oracle kind; empty when the case predates oracles (read defensively).

    ``oracle`` is either the kind string or a dict ``{kind, source, relation, verified}``."""
    raw = case.get("oracle")
    if isinstance(raw, dict):
        raw = raw.get("kind")
    return str(raw or "").strip().lower()


def oracle_verified(case: dict[str, Any]) -> bool:
    """The host-verified flag of a dict-shaped oracle; False for older string or missing oracles."""
    raw = case.get("oracle")
    return isinstance(raw, dict) and bool(raw.get("verified"))


def is_characterization(case: dict[str, Any]) -> bool:
    return oracle_kind(case) == "characterization"


def counts_as_verified(case: dict[str, Any]) -> bool:
    """Verified oracle, never characterization (current behaviour is not verified)."""
    return oracle_verified(case) and not is_characterization(case)


def documented_quote(case: dict[str, Any]) -> str:
    raw = case.get("oracle")
    if isinstance(raw, dict) and raw.get("quote"):
        return " ".join(str(raw["quote"]).split())
    for key in QUOTE_KEYS:
        value = " ".join(str(case.get(key) or "").split())
        if value:
            return value
    return ""


def is_verified(source_review: str, execution_status: str) -> bool:
    """Verified means both: the source review accepted the case AND it passed execution."""
    return source_review == "accepted" and execution_status == "passed"


def mismatch(message: str) -> tuple[str, str] | None:
    """(actual, expected) from an assertion message, or None when the message has no such pair."""
    for pattern in (_PYTEST_ASSERT, _EXPECTED_GOT):
        found = pattern.search(message or "")
        if not found:
            continue
        actual = found.group("actual").strip().strip("'\"")
        expected = found.group("expected").strip().strip("'\"")
        if actual and expected and actual != expected:
            return actual, expected
    return None


def classify_failure(
    message: str, *, oracle: str, quote: str, ecosystem: str | None = None
) -> dict[str, Any]:
    """Deterministic triage of one failure. Returns the class, the reason and the evidence used."""
    diagnoses = errors.classify(message or "", ecosystem or None)
    codes = [d.code for d in diagnoses]
    base: dict[str, Any] = {
        "oracle": oracle or None,
        "expected": None,
        "actual": None,
        "documented_quote": quote or None,
        "diagnoses": codes[:3],
    }
    if any(d.category in _ENVIRONMENT_CATEGORIES for d in diagnoses):
        return {**base, "classification": ENVIRONMENT, "reason": f"environment or setup failure ({codes[0]})"}
    if triage_rules.classify(message or "") == "test_defect":
        return {
            **base,
            "classification": TEST_DEFECT,
            "reason": "the generated test cannot run (import, name, syntax or compile error)",
        }
    pair = mismatch(message or "")
    if pair is None:
        return {
            **base,
            "classification": UNRESOLVED,
            "reason": "the failure is not an assertion with an actual and an expected value",
        }
    actual, expected = pair
    base.update(actual=actual, expected=expected)
    if oracle in DOCUMENTED_ORACLES:
        if quote and expected.lower() in quote.lower():
            return {
                **base,
                "classification": PRODUCT_DEFECT,
                "reason": f"actual {actual} differs from the documented expectation {expected} ({oracle})",
            }
        return {
            **base,
            "classification": TEST_DEFECT,
            "reason": f"the documented quote does not state {expected}, so the expectation was guessed",
        }
    if oracle in GUESSABLE_ORACLES:
        label = oracle or "missing"
        return {
            **base,
            "classification": TEST_DEFECT,
            "reason": f"oracle is {label}: the expected value {expected} was derived or guessed, not documented",
        }
    return {
        **base,
        "classification": UNRESOLVED,
        "reason": f"oracle {oracle} is not decided by the deterministic rules",
    }


def triage_cases(cases: list[dict[str, Any]], ecosystem: str | None = None) -> list[dict[str, Any]]:
    """One record per executed failure (status failed or error) with its class. ``cases`` are the report's rows, each
    carrying ``id``, ``status``, ``message``, ``oracle`` and ``oracle_quote``."""
    records = []
    for case in cases:
        if case.get("status") not in {"failed", "error"} or not case.get("message"):
            continue
        result = classify_failure(
            str(case["message"]),
            oracle=oracle_kind(case),
            quote=str(case.get("oracle_quote") or ""),
            ecosystem=ecosystem,
        )
        records.append({"case_id": case["id"], "status": case["status"], **result})
    return records


def summarize_triage(records: list[dict[str, Any]]) -> dict[str, int]:
    counts = dict.fromkeys(CLASSES, 0)
    for record in records:
        counts[record["classification"]] = counts.get(record["classification"], 0) + 1
    return counts
